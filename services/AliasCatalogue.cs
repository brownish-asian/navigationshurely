        private readonly Dictionary<int, string> _verseToAlias;


        private readonly Dictionary<string, List<KeyValuePair<string, int>>> _matchesByPrefix;

        public AliasCatalogue()
        {
            _verseToAlias = _aliasToVerse.ToDictionary(
                pair => pair.Value,
                pair => pair.Key);

            _matchesByPrefix = BuildMatchesByPrefix();
        }

        private Dictionary<string, List<KeyValuePair<string, int>>> BuildMatchesByPrefix()
        {
            var matchesByPrefix =
                new Dictionary<string, List<KeyValuePair<string, int>>>(
                    StringComparer.Ordinal);

            // Sort the aliases once, during initialisation.
            foreach (var pair in _aliasToVerse.OrderBy(
                pair => pair.Key,
                StringComparer.Ordinal))
            {
                // Build an entry for every possible partial alias.
                // For a four-letter alias, these are lengths 1, 2 and 3.
                for (int length = 1; length < pair.Key.Length; length++)
                {
                    string prefix = pair.Key[..length];

                    if (!matchesByPrefix.TryGetValue(prefix, out var matches))
                    {
                        matches = new List<KeyValuePair<string, int>>();
                        matchesByPrefix.Add(prefix, matches);
                    }

                    matches.Add(pair);
                }
            }

            return matchesByPrefix;
        }

        public bool TryResolve(string alias, out int position)
        {
            return _aliasToVerse.TryGetValue(alias, out position);
        }

        public bool IsPrefix(string prefix)
        {
            return _matchesByPrefix.ContainsKey(prefix);
        }

        public string? FindAlias(int encodedVerse)
        {
            if (_verseToAlias.TryGetValue(encodedVerse, out string? alias))
                return alias;

            return null;
        }

        public IReadOnlyList<KeyValuePair<string, int>> FindMatches(string prefix)
        {
            if (_matchesByPrefix.TryGetValue(prefix, out var matches))
                return matches;

            return Array.Empty<KeyValuePair<string, int>>();
        }
